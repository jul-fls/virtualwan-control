// Headless test for this app only. Never run against a live-mode console.
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const {chromium} = require(process.env.PLAYWRIGHT_CORE || 'playwright-core');
const url = process.env.VWAN_TEST_URL || 'http://localhost:8786';
assert(['localhost','127.0.0.1'].includes(new URL(url).hostname),'Only a local development server is allowed');
const out = process.env.VWAN_TEST_OUTPUT || 'data/browser-review';
fs.mkdirSync(out,{recursive:true});
(async()=>{
  const browser=await chromium.launch({headless:true,executablePath:process.env.BROWSER_EXECUTABLE});
  const context=await browser.newContext({viewport:{width:1480,height:1050},locale:'fr-FR'});
  const page=await context.newPage();const errors=[];
  page.on('pageerror',e=>errors.push(e.message));
  await context.route('**/*',route=>new URL(route.request().url()).origin===new URL(url).origin?route.continue():route.abort());
  await page.route('**/api/catalogue/*/configure',async route=>{const response=await route.fetch();const data=await response.json();if(route.request().postDataJSON().kind==='additional_ip'){for(const label of ['nexthop','nic','TECH_ACCOUNT','ADMIN_ACCOUNT'])data.fields.push({label,item_id:1,required:false,values:[]});}await route.fulfill({response,json:data});});
  await page.route('**/api/catalogue/*/router',async route=>{const response=await route.fetch();const data=await response.json();const base=data.offers[0];const variant=(planCode,ram,cpu,disk,value,duration)=>({...base,planCode,name:planCode,technical:{cpu:{cores:cpu},memory:{size:ram},storage:{disks:[{capacity:disk,technology:'SSD'}]}},pricings:[{duration,pricingMode:'default',price:{currencyCode:'EUR',value}}]});data.offers.push(variant('DEMO-small',2,1,20,1,'P1M'),variant('DEMO-large',16,8,150,48,'P1Y'));await route.fulfill({response,json:data});});
  try{
    await page.goto(url);
    await page.locator('#login-form input[name=username]').fill('admin');
    await page.locator('#login-form input[name=password]').fill(process.env.VWAN_TEST_PASSWORD);
    await page.locator('#login-form button').click();
    await page.locator('#shell').waitFor({state:'visible'});
    const s=await page.evaluate(async()=>await (await fetch('/api/state')).json());
    assert.equal(s.demo,true,'Refuse to exercise deployment/purchase UI in live mode');
    await page.screenshot({path:path.join(out,'overview.png'),fullPage:true});
    for(const section of ['clients','ips','routers','models','purchases','jobs','settings']){
      await page.locator('nav a[data-page='+section+']').click();
      assert((await page.locator('#page-title').textContent()).length>0);
      await page.screenshot({path:path.join(out,section+'.png'),fullPage:true});
    }
    await page.locator('nav a[data-page=ips]').click();
    await page.locator('[data-action=use-ip]').first().click();
    await page.locator('#action-form textarea[name=public_key]').fill('ssh-ed25519 AAAAC3NzaC1lZDI1NTE5AAAAIAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAA test');
    await page.locator('#action-form input[name=customer]').fill('Browser test — simulated');
    await page.screenshot({path:path.join(out,'new-client.png'),fullPage:true});
    await page.locator('#action-form button.primary').click();
    await page.waitForFunction(()=>!document.querySelector('#modal').open);
    await page.waitForFunction(async()=>{const s=await(await fetch('/api/state')).json();return s.deployments.some(d=>d.customer==='Browser test — simulated'&&d.status==='simulated');});
    await page.locator('nav a[data-page=purchases]').click();
    await page.locator('[data-action=new-quote]').click();
    await page.locator('#catalogue option[value="DEMO-ip"]').waitFor({state:'attached'});
    await page.locator('#catalogue').selectOption('DEMO-ip');
    assert((await page.locator('#quote-pricing').textContent()).includes('1 mois'));
    assert(!(await page.locator('#quote-pricing').textContent()).includes('0 jour'));
    assert((await page.locator('#quote-pricing').textContent()).includes('2,00'));
    await page.locator('#configure-offer').click();
    await page.locator('#cfg-1-country').selectOption('FR');
    assert.equal(await page.locator('#ip-advanced').getAttribute('open'),null);
    assert.equal(await page.locator('#ip-advanced input').count(),4);
    await page.locator('#ip-advanced summary').click();
    assert((await page.locator('#ip-advanced').textContent()).includes('Ne pas mettre le next-hop privé'));
    await page.locator('#ip-advanced summary').click();
    await page.screenshot({path:path.join(out,'ip-quote-form.png'),fullPage:true});
    await page.locator('#action-form button.primary').click();
    await page.waitForFunction(()=>!document.querySelector('#modal').open);
    await page.waitForFunction(async()=>{const s=await(await fetch('/api/state')).json();return s.purchases.some(p=>p.state==='awaiting_approval');});
    await page.locator('#refresh').click();
    await page.getByRole('button',{name:'Examiner & confirmer'}).first().click();
    await page.screenshot({path:path.join(out,'approval.png'),fullPage:true});
    // Stop before confirming: integration tests cover the simulated approval API.
    await page.locator('#close-modal').click();
    const before=await page.evaluate(async()=>await(await fetch('/api/state')).json());
    const client=before.deployments.find(d=>d.customer==='Browser test — simulated');
    await page.locator('[data-action=retire][data-mode=release][data-id="'+client.id+'"]').click();
    await page.locator('#action-form input[name=confirmation]').fill('LIBERER');
    await page.screenshot({path:path.join(out,'retire-client.png'),fullPage:true});
    await page.locator('#action-form button.primary').click();
    await page.waitForFunction(async(id)=>{const s=await(await fetch('/api/state')).json();return s.deployments.some(d=>d.id===id&&d.status==='detached'&&d.ip===null);},client.id);
    await page.locator('#refresh').click();
    await page.locator('[data-action=retire][data-mode=delete][data-id="'+client.id+'"]').click();
    await page.locator('#action-form input[name=confirmation]').fill('SUPPRIMER');
    await page.locator('#action-form button.primary').click();
    await page.waitForFunction(async(id)=>{const s=await(await fetch('/api/state')).json();return !s.deployments.some(d=>d.id===id);},client.id);
    await page.locator('[data-action=new-quote]').click();
    await page.locator('#quote-kind').selectOption('router');
    await page.locator('#new-router-name').fill('Routeur SSD — test simulé');
    await page.locator('#new-router-network').fill('10.254.252.0/24');
    await page.locator('#new-router-gateway').fill('10.254.252.1');
    await page.locator('#create-router-profile').click();
    await page.locator('#catalogue option[value="DEMO-router"]').waitFor({state:'attached'});
    const codes=()=>page.locator('#catalogue option').evaluateAll(rows=>rows.map(o=>o.value).filter(Boolean));
    assert.deepEqual(await codes(),['DEMO-small','DEMO-router','DEMO-large']);
    assert((await page.locator('#catalogue option[value="DEMO-router"]').textContent()).includes('2,00'));
    assert((await page.locator('#catalogue option[value="DEMO-large"]').textContent()).includes('4,00'));
    assert((await page.locator('#catalogue option[value="DEMO-large"]').textContent()).includes('équiv.'));
    await page.locator('#offer-sort').selectOption('ram');await page.locator('#offer-order').selectOption('desc');
    assert.deepEqual(await codes(),['DEMO-large','DEMO-router','DEMO-small']);
    await page.locator('#cpu-filter').selectOption('4');await page.locator('#memory-filter').selectOption('8');await page.locator('#disk-filter').selectOption('75');
    assert.deepEqual(await codes(),['DEMO-router']);
    await page.locator('#cpu-filter').selectOption('');await page.locator('#memory-filter').selectOption('');await page.locator('#disk-filter').selectOption('');
    await page.locator('#offer-sort').selectOption('storage');await page.locator('#offer-order').selectOption('asc');
    assert.deepEqual(await codes(),['DEMO-small','DEMO-router','DEMO-large']);
    await page.locator('#catalogue').selectOption('DEMO-router');
    await page.locator('[data-option-family=additionalDisk]').selectOption('DEMO-disk');
    await page.locator('#configure-offer').click();
    await page.locator('#cfg-1-vps_datacenter').selectOption('GRA');
    await page.screenshot({path:path.join(out,'router-quote-form.png'),fullPage:true});
    await page.locator('#action-form button.primary').click();
    await page.waitForFunction(()=>!document.querySelector('#modal').open);
    await page.waitForFunction(async()=>{const s=await(await fetch('/api/state')).json();return s.purchases.some(p=>p.kind==='router'&&p.state==='awaiting_approval');});
    await page.setViewportSize({width:390,height:844});
    await page.goto(url+'/#overview');
    await page.locator('#shell').waitFor({state:'visible'});
    await page.screenshot({path:path.join(out,'mobile.png'),fullPage:true});
    assert.deepEqual(errors,[]);
    console.log(JSON.stringify({pass:true,pages:8,simulated_client_deployed:true,quote_ready:true,router_quote_with_options:true,simulated_client_retired:true,approval_sent:false,console_errors:errors,screenshots:out}));
  }finally{await context.close();await browser.close();}
})().catch(e=>{console.error(e.stack);process.exit(1)});
